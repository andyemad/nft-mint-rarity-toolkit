def typo(s):
    """French typography: narrow no-break space before : ; ! ? and inside « »,
    typographic apostrophes."""
    s = s.replace("'", "\u2019")
    s = s.replace("« ", "«" + NBSP).replace(" »", NBSP + "»")
    for ch in (";", "!", "?", ":"):
        s = s.replace(" " + ch, NBSP + ch)
    return s


def main():
    with open(SRC, encoding="utf-8") as fh:
        src = json.load(fh)

    strings = src["strings"]
    attrs = src["attrs"]

    missing_text = [i for i in range(len(strings)) if i not in TEXT]
    extra_text = [i for i in TEXT if i not in range(len(strings))]
    missing_attr = [i for i in range(len(attrs)) if i not in ATTR]
    extra_attr = [i for i in ATTR if i not in range(len(attrs))]
    if missing_text or extra_text or missing_attr or extra_attr:
        raise SystemExit(
            "index mismatch: text missing=%s extra=%s attr missing=%s extra=%s"
            % (missing_text, extra_text, missing_attr, extra_attr)
        )

    head_missing = [k for k in src["head"] if k not in HEAD]
    head_extra = [k for k in HEAD if k not in src["head"]]
    js_missing = [k for k in src["js_defaults"] if k not in JS]
    js_extra = [k for k in JS if k not in src["js_defaults"]]
    if head_missing or head_extra or js_missing or js_extra:
        raise SystemExit(
            "key mismatch: head missing=%s extra=%s js missing=%s extra=%s"
            % (head_missing, head_extra, js_missing, js_extra)
        )

    text = {s: typo(TEXT[i]) for i, s in enumerate(strings)}
    attr = {s: typo(ATTR[i]) for i, s in enumerate(attrs)}
    head = {k: typo(HEAD[k]) for k in src["head"]}
    js = {k: typo(JS[k]) for k in src["js_defaults"]}

    out = {
        "lang": "fr",
        "name": "Français",
        "dir": "ltr",
        "text": text,
        "attr": attr,
        "head": head,
        "js": js,
    }
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=1)
        fh.write("\n")

    # verification
    written = json.load(open(OUT, encoding="utf-8"))
    assert written["text"].keys() == set(strings), "text keys differ"
    assert written["attr"].keys() == set(attrs), "attr keys differ"
    assert written["head"].keys() == set(src["head"]), "head keys differ"
    assert written["js"].keys() == set(src["js_defaults"]), "js keys differ"
    assert "{n}" in written["js"]["progress.count"], "{n} lost"
    for bucket, src_map in (
        ("text", text),
        ("attr", attr),
        ("head", head),
        ("js", js),
    ):
        for k, v in src_map.items():
            assert v.strip(), "empty value for %r in %s" % (k[:40], bucket)

