# Brand / technical tokens that must survive translation verbatim. Used as an
# alignment check: if the value list were shifted by one, these would break.
BRANDS = [
    "Hermes", "Discord", "OpenCode", "GitHub", "Vercel", "Modal", "Ubuntu",
    "Hashcats", "FAB4200", "Nous", "Windows", "Mac", "Linux", "OpenSea",
    "Hetzner", "DigitalOcean", "Cloudflare", "Google", "Pirate", "ETH",
    # "Bot" is deliberately absent: as a Discord UI label it stays "Bot"
    # (string 131), but as a common noun the Hebrew text says "הבוט".
    "PowerShell", "Terminal", "Installation", "Agents", "APP", "@hermes",
    "opencode.ai", "modal.com", "vercel.com/signup", "portal.nousresearch.com",
    "discord.com/developers/applications", "Y",
]
TOKEN_RE = re.compile(r"[A-Za-z@][A-Za-z0-9@.+:/_-]*")


def check_alignment(src, txt):
    """Every brand token in a source string must appear in its translation."""
    problems = []
    for i, (s, t) in enumerate(zip(src, txt), 1):
        for m in TOKEN_RE.finditer(s):
            tok = m.group(0)
            if tok in BRANDS and tok not in t:
                problems.append((i, tok, s, t))
    return problems


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    src_text, src_attr, src_head = data["strings"], data["attrs"], data["head"]
    js_keys = data["js_keys"]

    errs = []
    if len(src_text) != len(TEXTS):
        errs.append(f"text: {len(TEXTS)} translations for {len(src_text)} strings")
    if len(src_attr) != len(ATTRS):
        errs.append(f"attr: {len(ATTRS)} translations for {len(src_attr)} attrs")
    if len(js_keys) != len(JS_VALUES):
        errs.append(f"js: {len(JS_VALUES)} values for {len(js_keys)} keys")
    for k in src_head:
        if k not in HEAD:
            errs.append(f"head: missing {k}")
    if errs:
        sys.exit("aborting:\n  " + "\n  ".join(errs))

    text = dict(zip(src_text, TEXTS))
    attr = dict(zip(src_attr, ATTRS))
    js = dict(zip(js_keys, JS_VALUES))

    align = check_alignment(src_text, TEXTS)
    if align:
        print("ALIGNMENT WARNINGS (index, token, source):")
        for i, tok, s, t in align:
            print(f"  [{i}] {tok}: {s!r}")
        print(f"  total: {len(align)}")
    if len(text) != len(src_text):
        sys.exit(f"duplicate source strings collapse the dict: "
                 f"{len(text)} != {len(src_text)}")

    for bucket, src, dst in (("text", src_text, TEXTS), ("attr", src_attr, ATTRS)):
        missing = [s for s in src if not dst[src.index(s)].strip()]
        if missing:
            sys.exit(f"empty translations in {bucket}: {missing[:5]}")

    out = {"lang": "he", "name": "עברית", "dir": "rtl",
           "text": text, "attr": attr, "head": HEAD, "js": js}
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=1)

    print(f"text : {len(text)}")
    print(f"attr : {len(attr)}")
    print(f"head : {len(HEAD)}")
    print(f"js   : {len(js)}")
    print(f"wrote: {OUT}")
    # A few spot checks so drift is visible at a glance.
    for i in (0, 13, 26, 130, 250, 375, 502):
        print(f"  #{i + 1}: {src_text[i]!r} -> {TEXTS[i]!r}")


if __name__ == "__main__":
    main()
